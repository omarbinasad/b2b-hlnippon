/**
 * Writes docs/FRONTEND-ROUTE-MAP.md from the app folder and the capability table: every page, who may open it, and the
 * data it reads.
 *
 *   npm run docs:routes
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { capabilityForPath } from "../src/lib/auth/capabilities.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const APP = join(ROOT, "src/app");

function walk(dir: string, out: string[] = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name === "page.tsx" || name === "route.ts" || name === "route.tsx") out.push(p);
  }
  return out;
}

const urlOf = (file: string) => {
  const parts = relative(APP, dirname(file)).split(/[\\/]/).filter((s) => s && !/^\(.*\)$/.test(s));
  return `/${parts.join("/")}`;
};

function reads(file: string) {
  const source = readFileSync(file, "utf8");
  const calls = [...source.matchAll(/repositories\.(\w+)\.(\w+)\(/g)].map((m) => `${m[1]}.${m[2]}`);
  return [...new Set(calls)];
}

function audience(url: string) {
  if (url.startsWith("/admin")) return capabilityForPath(url) ?? "staff";
  if (url.startsWith("/account") || url === "/cart" || url === "/checkout" || url.startsWith("/checkout")) return "signed-in customer";
  if (url.startsWith("/preview")) return "staff";
  return "public";
}

const AREAS: [string, (u: string) => boolean][] = [
  ["Admin", (u) => u.startsWith("/admin")],
  ["Customer portal", (u) => u.startsWith("/account")],
  ["Sign-in", (u) => /^\/(login|register|forgot-password|reset-password)/.test(u)],
  ["Storefront and other", () => true],
];

const files = walk(APP);
const pages = files.filter((f) => f.endsWith("page.tsx")).map((f) => ({ url: urlOf(f), who: audience(urlOf(f)), reads: reads(f), file: relative(ROOT, f).replace(/\\/g, "/") }));
const handlers = files.filter((f) => !f.endsWith("page.tsx")).map((f) => ({ url: urlOf(f), file: relative(ROOT, f).replace(/\\/g, "/") }));
pages.sort((a, b) => a.url.localeCompare(b.url));

const out = [
  "# Frontend route map",
  "",
  `${pages.length} pages and ${handlers.length} route handlers. Generated by \`npm run docs:routes\`. Don't edit by hand.`,
  "",
  "**Who** is what the demo's route guard shows, from `capabilityForPath` in `src/lib/auth/capabilities.ts`, for staff, or the viewer type for everyone else. It only controls what the screen shows. The backend must check every call: see [ROLES-AND-CAPABILITIES.md](ROLES-AND-CAPABILITIES.md).",
  "",
  "**Reads** lists the repository calls in the page's own file, not those of its components. Each maps to an endpoint in [API-CONTRACTS.md](API-CONTRACTS.md).",
  "",
];
const left = new Set(pages);
for (const [title, test] of AREAS) {
  const rows = [...left].filter((p) => test(p.url));
  if (!rows.length) continue;
  rows.forEach((r) => left.delete(r));
  out.push(`## ${title}`, "", "| URL | Who | Reads |", "|---|---|---|");
  for (const r of rows) out.push(`| \`${r.url}\` | ${r.who} | ${r.reads.map((x) => `\`${x}\``).join(", ")} |`);
  out.push("");
}
out.push("## Route handlers", "", "| URL | File |", "|---|---|");
for (const h of handlers) out.push(`| \`${h.url}\` | \`${h.file}\` |`);
writeFileSync(join(ROOT, "docs/FRONTEND-ROUTE-MAP.md"), `${out.join("\n")}\n`);
if (process.env.ROUTE_LIST_OUT) writeFileSync(process.env.ROUTE_LIST_OUT, JSON.stringify(pages.map((p) => p.url)));
console.log(`${pages.length} pages, ${handlers.length} handlers.`);
