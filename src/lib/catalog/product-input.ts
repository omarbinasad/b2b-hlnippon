/**
 * A saved product as editable input: what the product editor would submit unchanged. Used to update part of a product
 * (CSV import) without losing the rest. Pure and tested.
 */
import type { Product, ProductInput, StockStatus } from "../types/index.ts";

/** Stock status that can be chosen by hand ("low stock" is derived, never chosen). */
const manualStatus = (s?: StockStatus): StockStatus => (s === "low_stock" || !s ? "in_stock" : s);

export function productToInput(p: Product, tagName: (id: string) => string = (id) => id): ProductInput {
  return {
    type: p.type,
    name: p.name,
    slug: p.slug,
    sku: p.sku,
    gtin: p.gtin,
    shortDescription: p.shortDescription,
    description: p.description,
    status: p.status,
    visibility: p.visibility,
    featured: p.featured,
    categoryIds: [...p.categoryIds],
    tags: (p.tagIds ?? []).map(tagName),
    brandIds: [...p.brandIds],
    images: p.images.map((i) => ({ ...i })),
    originCountry: p.originCountry,
    unitLabel: p.unitLabel,
    basePrice: p.basePrice,
    salePrice: p.salePrice,
    saleFrom: p.saleFrom,
    saleTo: p.saleTo,
    taxStatus: p.taxStatus,
    taxClass: p.taxClass,
    manageStock: p.manageStock,
    stockQuantity: p.manageStock ? p.stock.quantity : undefined,
    stockStatus: manualStatus(p.stock.status),
    backorders: p.backorders,
    lowStockThreshold: p.lowStockThreshold,
    soldIndividually: p.soldIndividually,
    minQuantity: p.quantityRule.min,
    maxQuantity: p.quantityRule.max,
    quantityStep: p.quantityRule.step,
    initialStock: p.initialStock,
    unitOfMeasure: p.unitOfMeasure,
    weight: { ...p.weight },
    dimensions: p.dimensions ? { ...p.dimensions } : undefined,
    shippingClassId: p.shippingClassId,
    isVariableWeight: p.isVariableWeight,
    attributes: p.attributes.map((a) => ({ ...a, values: [...a.values] })),
    defaultAttributes: { ...p.defaultAttributes },
    variations: p.variations.map((v) => ({
      id: v.id,
      sku: v.sku,
      gtin: v.gtin,
      attributes: { ...v.attributes },
      status: v.status,
      basePrice: v.basePrice,
      salePrice: v.salePrice,
      saleFrom: v.saleFrom,
      saleTo: v.saleTo,
      image: v.image ? { ...v.image } : undefined,
      gallery: v.gallery.map((g) => ({ ...g })),
      description: v.description,
      stockMode: v.stockMode,
      stockQuantity: v.stockMode === "track" ? v.stock.quantity : undefined,
      stockStatus: manualStatus(v.stock.status),
      backorders: v.backorders,
      weight: v.weight ? { ...v.weight } : undefined,
      dimensions: v.dimensions ? { ...v.dimensions } : undefined,
      shippingClassId: v.shippingClassId,
      taxClass: v.taxClass,
    })),
    upsellIds: [...p.upsellIds],
    crossSellIds: [...p.crossSellIds],
    purchaseNote: p.purchaseNote,
    menuOrder: p.menuOrder,
    reviewsEnabled: p.reviewsEnabled,
  };
}
